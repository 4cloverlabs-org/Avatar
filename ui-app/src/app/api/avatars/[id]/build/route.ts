import { NextResponse } from 'next/server';
import fs from 'fs';
import path from 'path';
import { Client, handle_file } from '@gradio/client';

export async function POST(
  request: Request,
  { params }: { params: { id: string } }
) {
  try {
    const trackingId = params.id;
    const trackingDir = path.join(process.cwd(), '..', 'results', 'avatars', trackingId);

    if (!fs.existsSync(trackingDir)) {
      return NextResponse.json({ success: false, error: 'Avatar not found' }, { status: 404 });
    }

    const videoPath = path.join(trackingDir, 'video.mp4');
    if (!fs.existsSync(videoPath)) {
      return NextResponse.json({ success: false, error: 'Video not found' }, { status: 404 });
    }

    const formData = await request.formData().catch(() => new FormData());
    const bboxShift = Number(formData.get('bboxShift')) || 0;
    const extraMargin = Number(formData.get('extraMargin')) || 10;
    const parsingMode = (formData.get('parsingMode') as string) || 'jaw';
    const leftCheekWidth = Number(formData.get('leftCheekWidth')) || 90;
    const rightCheekWidth = Number(formData.get('rightCheekWidth')) || 90;

    // Create a File object from the buffer
    const buffer = fs.readFileSync(videoPath);
    const videoFile = new File([buffer], 'video.mp4', { type: 'video/mp4' });

    // Simulate progress while the backend runs
    const trackingMetaPath = path.join(trackingDir, 'meta.json');
    let simulatedProgress = 5;
    
    const progressInterval = setInterval(() => {
      if (simulatedProgress < 99) {
        simulatedProgress += Math.floor(Math.random() * 3) + 1; // Slower increment to span both tasks
        if (simulatedProgress > 99) simulatedProgress = 99;
        
        if (fs.existsSync(trackingMetaPath)) {
          try {
            const meta = JSON.parse(fs.readFileSync(trackingMetaPath, 'utf8'));
            meta.progress = simulatedProgress;
            fs.writeFileSync(trackingMetaPath, JSON.stringify(meta, null, 2));
          } catch (e) {}
        }
      }
    }, 4000); // Update every 4 seconds

    let realAvatarId: string | null = null;
    
    console.log(`[Avatar Build] Starting backend build for tracking ID ${trackingId}...`);
    const client = await Client.connect("http://127.0.0.1:7860");
    
    try {
      // This blocks until python finishes
      const result = await client.predict("/prepare_avatar", [ 
        { video: handle_file(videoFile) },
        bboxShift,
        extraMargin,
        parsingMode,
        leftCheekWidth,
        rightCheekWidth
      ]);
      
      realAvatarId = result.data[0] as string;
    } finally {
      clearInterval(progressInterval);
    }

    if (!realAvatarId) {
      throw new Error("Did not receive avatar ID from backend");
    }

    console.log(`[Avatar Build] Backend build complete. Real Avatar ID: ${realAvatarId}. Merging...`);

    const realDir = path.join(process.cwd(), '..', 'results', 'avatars', realAvatarId);
    
    // Copy/Move all files from realDir to trackingDir, except we merge meta.json
    if (fs.existsSync(realDir)) {
      const files = fs.readdirSync(realDir);
      for (const file of files) {
        if (file === 'meta.json') continue;
        const srcPath = path.join(realDir, file);
        const destPath = path.join(trackingDir, file);
        if (fs.statSync(srcPath).isDirectory()) {
          // copy directory
          fs.cpSync(srcPath, destPath, { recursive: true });
        } else {
          fs.copyFileSync(srcPath, destPath);
        }
      }

      // Merge meta.json
      const trackingMetaPath = path.join(trackingDir, 'meta.json');
      const realMetaPath = path.join(realDir, 'meta.json');
      
      let trackingMeta = {};
      let realMeta = {};
      
      if (fs.existsSync(trackingMetaPath)) {
        trackingMeta = JSON.parse(fs.readFileSync(trackingMetaPath, 'utf8'));
      }
      if (fs.existsSync(realMetaPath)) {
        realMeta = JSON.parse(fs.readFileSync(realMetaPath, 'utf8'));
      }
      
      const mergedMeta = {
        ...trackingMeta,
        ...realMeta,
        status: 'ready',
        id: trackingId // Keep the tracking ID as the actual ID now
      };
      
      fs.writeFileSync(trackingMetaPath, JSON.stringify(mergedMeta, null, 2));

      // Clean up the realDir generated by Python
      fs.rmSync(realDir, { recursive: true, force: true });
    }
    
    console.log(`[Avatar Build] Preparing preview video for ${trackingId}...`);
    try {
      const audioPath = path.join(process.cwd(), '..', 'data', 'audio', 'yongen.wav');
      const audioBuffer = fs.readFileSync(audioPath);
      const audioFile = new File([audioBuffer], 'yongen.wav', { type: 'audio/wav' });

      await client.predict("/generate_from_avatar", [
        trackingId, // Using trackingId because we merged the files into the tracking directory
        handle_file(audioFile),
        true, // use_gfpgan
        0.5   // gfpgan_weight
      ]);
      
      const genPath = path.join(trackingDir, 'output', 'final_yongen.mp4');
      if (fs.existsSync(genPath)) {
        fs.copyFileSync(genPath, path.join(trackingDir, 'preview_ai.mp4'));
      }
    } catch(e) {
      console.error("[Avatar Build] Failed to generate AI preview:", e);
    }

    console.log(`[Avatar Build] Finished entirely for ${trackingId}`);
    
    return NextResponse.json({ success: true, avatarId: trackingId });
  } catch (error: any) {
    console.error("[Avatar Build] API Route Error:", error);
    // Mark as failed if possible
    try {
      const trackingMetaPath = path.join(process.cwd(), '..', 'results', 'avatars', params.id, 'meta.json');
      if (fs.existsSync(trackingMetaPath)) {
        const meta = JSON.parse(fs.readFileSync(trackingMetaPath, 'utf8'));
        meta.status = 'error';
        fs.writeFileSync(trackingMetaPath, JSON.stringify(meta, null, 2));
      }
    } catch (e) {}
    
    return NextResponse.json({ success: false, error: error.message || "Failed to build avatar" }, { status: 500 });
  }
}
